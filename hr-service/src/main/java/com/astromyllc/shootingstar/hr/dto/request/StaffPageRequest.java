package com.astromyllc.shootingstar.hr.dto.request;

/**
 * Asks for one page of a school's staff.
 * The school is always set by the ORB proxy from the signed-in user, never by the browser.
 */
public class StaffPageRequest {
    private String institutionCode;
    private String search;
    private String sortBy;
    private String sortDir;
    private Integer page;
    private Integer size;

    public String getInstitutionCode() {
        return institutionCode;
    }

    public void setInstitutionCode(String institutionCode) {
        this.institutionCode = institutionCode;
    }

    public String getSearch() {
        return search;
    }

    public void setSearch(String search) {
        this.search = search;
    }

    public String getSortBy() {
        return sortBy;
    }

    public void setSortBy(String sortBy) {
        this.sortBy = sortBy;
    }

    public String getSortDir() {
        return sortDir;
    }

    public void setSortDir(String sortDir) {
        this.sortDir = sortDir;
    }

    public Integer getPage() {
        return page;
    }

    public void setPage(Integer page) {
        this.page = page;
    }

    public Integer getSize() {
        return size;
    }

    public void setSize(Integer size) {
        this.size = size;
    }
}
